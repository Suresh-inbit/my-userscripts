#!/usr/bin/env python3
"""Build iitm-placement-mobile.js = the desktop userscript + mobile/mobile.css + mobile/mobile.js.

Run after every change to iitm-placement-enhancer.js or mobile/*. The generated file shares the desktop version.
"""
import os
import re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def read(name):
    with open(os.path.join(root, name), encoding='utf-8') as f:
        return f.read()


src = read('iitm-placement-enhancer.js')
version = re.search(r'@version\s+(\S+)', src).group(1)
body = src.split('// ==/UserScript==\n', 1)[1]
css = read('mobile/mobile.css')
js = read('mobile/mobile.js')
assert '`' not in css and '${' not in css, 'mobile.css must not contain backticks or ${'
for marker in ('/*__MOBILE_CSS__*/', '/*__MOBILE_JS__*/'):
    assert body.count(marker) == 1, marker
body = body.replace('/*__MOBILE_CSS__*/', css.rstrip('\n')).replace('/*__MOBILE_JS__*/', js.rstrip('\n'))

header = f"""// ==UserScript==
// @name         IITM Placement Portal — Mobile
// @namespace    suresh.iitm.placement.mobile
// @version      {version}
// @description  Phone-friendly Clean Dashboard for placement.iitm.ac.in/students*: card layout, swipeable navbar, big touch targets. Install this INSTEAD of the desktop script, not together with it.
// @match        https://placement.iitm.ac.in/students*
// @run-at       document-start
// @grant        none
// ==/UserScript==
// GENERATED by mobile/build.py from iitm-placement-enhancer.js + mobile/ -- edit those, not this file.
"""
with open(os.path.join(root, 'iitm-placement-mobile.js'), 'w', encoding='utf-8') as f:
    f.write(header + body)
print('built iitm-placement-mobile.js v' + version)
